# ── Onde criar um card novo quando o código não existe ainda no HTML ──
# Prefixos sem ambiguidade: sempre vão para o mesmo lugar, não importa o texto.
# Não existe prefixo de código que garanta a seção sozinho - até COMPRO
# tem itens de Alimentos Preparados (ex: bolinhos, empanados) E itens de
# Congelados (ex: galinha/galo inteiro). A classificação é sempre feita
# lendo a descrição do produto, em classificar_produto_novo() abaixo.


def _sem_acento(txt):
    import unicodedata
    return "".join(
        c for c in unicodedata.normalize("NFD", txt)
        if unicodedata.category(c) != "Mn"
    )


def classificar_produto_novo(nome_produto):
    """Decide em qual seção/grupo do painel um produto novo deve entrar,
    lendo palavras-chave do nome/descrição do ERP. A descrição é o único
    sinal confiável - o prefixo/código NÃO indica a seção (ex: COMPRO tem
    tanto "Galinha Inteira Congelada" -> Congelados/Inteiros quanto
    "Sassami Empanado" -> Alimentos Preparados).
    Retorna (secao, grupo_label) ou None se não conseguir decidir com
    segurança (nesse caso o script só avisa no log, não cria o card)."""
    nome = _sem_acento(nome_produto or "").upper()

    # Alimentos Preparados: itens processados/prontos, mesmo que a
    # descrição também diga "CONGELADO" (ex: batata congelada, empanados).
    # Esse sinal tem prioridade sobre o corte de frango, porque um "Fut
    # Chicken" ou uma "Lasanha" não são pedaços de frango in natura.
    sinais_alimentos = (
        "EMPANAD", "CHICKEN", "BATATA", "MANDIOCA", "POLENTA",
        "ANEL DE CEBOLA", "PAO DE QUEIJO", "LASANHA", "TILAPIA", "PEIXE",
        "FISH", "BURGUER", "BOLINHO", "WINGS", "NUGGET", "ISCA DE",
        "HAMBURGUER", "STEAK", "NOISETTE", "KIBE", "QUIBE", "ESPETO",
        "GOLDEN", "PIZZA", "TORTA", "PASTEL", "COXINHA DE FRANGO PRE FRITA",
    )
    if any(k in nome for k in sinais_alimentos):
        return ("alimentos", "ALIMENTOS")

    if "IQF" in nome:
        return ("iqf", "IQF")

    if "RESFR" in nome:
        grupo = "BANDEJA" if ("BANDEJA" in nome or "BDJ" in nome) else "PACOTE"
        return ("resfriados", grupo)

    if "CONG" in nome:
        eh_bandeja = "BANDEJA" in nome or "BDJ" in nome
        if eh_bandeja:
            return ("congelados", "GRUPO BANDEJA CONGELADA")
        if any(k in nome for k in ("INTEIR", "GALINHA", "GALO", "CARCACA", "TEMPERAD")):
            return ("congelados", "GRUPO INTEIROS")
        if any(k in nome for k in ("ASA", "DRUMET")):
            return ("congelados", "GRUPO ASA")
        if any(k in nome for k in ("COXA", "SOBRECOXA", "PERNA", "DORSAL",
                                    "LEG QUARTER", "TULIPA", "QUARTO DE PERNA")):
            return ("congelados", "GRUPO PERNA")
        if any(k in nome for k in ("PEITO", "FILE", "FILEZINHO", "SASSAMI")):
            return ("congelados", "GRUPO PEITO")
        if any(k in nome for k in ("CORACAO", "FIGADO", "MOELA", "PESCOCO", "CMS",
                                    "PES ", "SAMBIQUIRA", "MIUDO", "CARTILAGEM",
                                    "MOLA", "PAPADA", "CRISTA", "MIUDEZA")):
            return ("congelados", "GRUPO MIUDOS")
        # é congelado mas o corte especifico nao bateu com nenhuma palavra-chave
        return None

    return None


# ── Seções/grupos válidos - usados tanto pelas regras de palavra-chave acima
# quanto pelo fallback de IA abaixo, pra nunca inventar um grupo que não
# existe de fato no painel. ──
SECOES_VALIDAS = {
    "resfriados": ["BANDEJA", "PACOTE"],
    "congelados": [
        "GRUPO ASA", "GRUPO BANDEJA CONGELADA", "GRUPO INTEIROS",
        "GRUPO MIUDOS", "GRUPO PEITO", "GRUPO PERNA",
    ],
    "iqf": ["IQF"],
    "alimentos": ["ALIMENTOS"],
}


def classificar_com_ia(nome_produto):
    """Fallback quando classificar_produto_novo() não consegue decidir por
    palavra-chave: manda a descrição do produto pra Claude e pede pra
    classificar, restrito às combinações de seção+grupo que já existem de
    fato no painel (SECOES_VALIDAS acima).

    Só roda se a secret ANTHROPIC_API_KEY estiver configurada no repositório.
    Qualquer situação que não dê 100% de segurança - sem chave configurada,
    erro de rede, resposta fora do formato esperado, ou o próprio modelo
    dizendo que não tem certeza - devolve None, e quem chamou (inserir_cards_novos)
    cai de volta pra seção 'Não Classificados' normalmente. Isso nunca trava
    nem atrasa a atualização do estoque em si."""
    api_key = os.environ.get("ANTHROPIC_API_KEY")
    if not api_key or not (nome_produto or "").strip():
        return None

    opcoes = "\n".join(
        f'- secao="{secao}", grupo="{grupo}"'
        for secao, grupos in SECOES_VALIDAS.items()
        for grupo in grupos
    )
    prompt = (
        "Você classifica produtos do estoque de um frigorífico (frango, "
        "peixe e alimentos preparados) em uma das combinações de seção+grupo "
        "abaixo, com base só na descrição do produto (texto cru do ERP, "
        "normalmente em maiúsculas e abreviado).\n\n"
        f"Combinações válidas (use exatamente uma delas):\n{opcoes}\n\n"
        f'Descrição do produto: "{nome_produto}"\n\n'
        "Responda SOMENTE com um JSON, sem nenhum texto antes ou depois, "
        'no formato {"secao": "...", "grupo": "..."}. Se não tiver certeza '
        'suficiente, responda {"secao": null, "grupo": null}.'
    )

    try:
        resp = requests.post(
            "https://api.anthropic.com/v1/messages",
            headers={
                "x-api-key": api_key,
                "anthropic-version": "2023-06-01",
                "content-type": "application/json",
            },
            json={
                "model": "claude-haiku-4-5",
                "max_tokens": 100,
                "messages": [{"role": "user", "content": prompt}],
            },
            timeout=20,
        )
        resp.raise_for_status()
        texto = resp.json()["content"][0]["text"].strip()
        m = re.search(r"\{.*\}", texto, re.S)
        if not m:
            return None
        obj = json.loads(m.group(0))
        secao, grupo = obj.get("secao"), obj.get("grupo")
        if secao in SECOES_VALIDAS and grupo in SECOES_VALIDAS[secao]:
            return (secao, grupo)
        return None
    except Exception as e:
        print(f"AVISO - classificação por IA falhou pra '{nome_produto}': {e}")
        return None



def baixar_csv(url):
    # Pede versão fresca: o CSV "publicado na web" do Google fica em cache por
    # alguns minutos, e como essa rodada normalmente começa poucos segundos
    # depois da planilha ser editada, sem isso é fácil ler a versão anterior
    # (sintoma: "editei a planilha e o site não mudou nada" - e aí a mudança
    # só aparece na rodada seguinte, de hora em hora).
    resp = requests.get(url, headers={
        "Cache-Control": "no-cache, max-age=0",
        "Pragma": "no-cache",
    }, timeout=60)
    resp.raise_for_status()
    resp.encoding = "utf-8"
    return resp.text


def carregar_validades(csv_text):
    """Lê a aba de validades (Cód. Prod. Cliente, Peso Líquido, Validade)
    e monta o mesmo formato usado no VALIDADES do HTML:
    { codigo: { entries: [{d, p, v}], hv: bool } }
    """
    reader = csv.reader(StringIO(csv_text))
    rows = list(reader)
    hoje = datetime.now(timezone.utc) - timedelta(hours=3)
    hoje = hoje.replace(hour=0, minute=0, second=0, microsecond=0, tzinfo=None)

    validades = {}
    for r in rows[2:]:
        if not r or not r[0]:
            continue
        codigo = r[0].strip()
        try:
            peso = float(str(r[1]).replace(".", "").replace(",", ".")) if r[1] else 0
        except (ValueError, IndexError):
            peso = 0
        data_str = r[2].strip() if len(r) > 2 else ""
        if not data_str:
            continue
        try:
            data_venc = datetime.strptime(data_str, "%d/%m/%Y")
        except ValueError:
            continue
        vencido = data_venc < hoje
        entry = {"d": data_str, "p": peso, "v": vencido}
        validades.setdefault(codigo, {"entries": [], "hv": False})
        validades[codigo]["entries"].append(entry)
        if vencido:
            validades[codigo]["hv"] = True
    return validades


def carregar_saldos(csv_text):
    """Retorna tanto os saldos quanto os dados brutos (nome, tp) de cada
    código, para permitir criar cards novos quando necessário."""
    reader = csv.reader(StringIO(csv_text))
    rows = list(reader)
    data = {}
    linhas_brutas = {}
    # linha 0 = título da planilha, linha 1 = cabeçalho, dados a partir da linha 2
    for r in rows[2:]:
        if not r or not r[0]:
            continue
        codigo = r[0].strip()
        try:
            disponivel = float(str(r[9]).replace(".", "").replace(",", ".")) if r[9] else 0
        except (ValueError, IndexError):
            disponivel = 0
        data[codigo] = disponivel
        linhas_brutas[codigo] = r
    return data, linhas_brutas


def _parse_num_br(txt):
    """Converte um número no formato brasileiro (2.250 = dois mil e
    duzentos e cinquenta; 2,25 = dois vírgula vinte e cinco) pra float.
    Retorna None se estiver vazio/ilegível - o front trata isso como "-"."""
    txt = (txt or "").strip()
    if not txt:
        return None
    try:
        return float(txt.replace(".", "").replace(",", "."))
    except ValueError:
        return None


def _data_para_ordenacao(data_str):
    """Linhas sem data de carregamento (ex: "PROGRAMADA" sem data ainda
    definida) vão pro fim da lista - as demais ficam em ordem cronológica."""
    try:
        return datetime.strptime((data_str or "").strip(), "%d/%m/%Y")
    except ValueError:
        return datetime.max


def carregar_programacao_cargas(csv_text):
    """Lê a planilha de programação de cargas (publicada como CSV) e agrupa
    as linhas por Código Protheus do produto - é isso que alimenta o botão
    "🚚 programação" de cada card do estoque, mostrando só as cargas
    daquele produto específico.

    Duas particularidades da planilha original (confirmadas com um export
    real dela) que essa função precisa tratar:

    1. Pode ter uma linha em branco antes do cabeçalho de verdade - por
       isso o cabeçalho é localizado procurando a linha que contém
       "CÓDIGO PROTHEUS", em vez de assumir que é sempre a linha 1.
    2. Os dados de cada "viagem" (FILIAL, DATA CARREGAMENTO, VIAGEM_MAE,
       STATUS, NF, DATA/HORA FAT., PLACAS, PEDIDO) só vêm preenchidos na
       primeira linha do carregamento; nas linhas seguintes (outros
       produtos da mesma carga) essas colunas ficam em branco - é o
       "preenche uma vez só" comum de planilha feita à mão. Por isso essas
       colunas são propagadas (forward-fill) da última linha em que
       apareceram preenchidas. GRUPO/EMBALAGEM, LOCAL DE EMBARQUE, CÓDIGO,
       CÓDIGO PROTHEUS, PRODUTO, Kg PROGR. e Kg FAT. sempre vêm
       preenchidas linha a linha (não são propagadas).
    """
    linhas_csv = list(csv.reader(StringIO(csv_text)))

    def _norm(h):
        return _sem_acento((h or "").strip().upper())

    idx_cabecalho = None
    for i, r in enumerate(linhas_csv):
        if any(_norm(c) in ("CODIGO PROTHEUS",) for c in r):
            idx_cabecalho = i
            break
    if idx_cabecalho is None:
        return {}, {}

    cabecalho = linhas_csv[idx_cabecalho]
    col_idx = {_norm(h): i for i, h in enumerate(cabecalho)}

    def _idx(*nomes):
        for nome in nomes:
            i = col_idx.get(_norm(nome))
            if i is not None:
                return i
        return None

    idx_data = _idx("DATA CARREGAMENTO")
    idx_viagem_mae = _idx("VIAGEM_MAE")
    idx_status = _idx("STATUS")
    idx_nf = _idx("NF")
    idx_data_hora_fat = _idx("DATA/HORA FAT.", "DATA/HORA FAT")
    idx_placas = _idx("PLACAS")
    idx_pedido = _idx("PEDIDO")
    idx_codigo_protheus = _idx("CÓDIGO PROTHEUS", "CODIGO PROTHEUS")
    idx_produto = _idx("PRODUTO")
    idx_kg_prog = _idx("KG PROGR.", "KG PROGR", "KG PROG.", "KG PROG")
    idx_kg_fat = _idx("KG FAT.", "KG FAT")

    def _cel(r, i):
        if i is None or i >= len(r):
            return ""
        return (r[i] or "").strip()

    # Propaga (forward-fill) os campos que descrevem a viagem/carga em si -
    # na planilha eles só vêm preenchidos na primeira linha de cada
    # carregamento; nas linhas seguintes (outros produtos da mesma carga)
    # ficam em branco e herdam o último valor visto.
    carry_data = carry_viagem_mae = carry_status = ""
    # PLACAS/PEDIDO/NF/DATA-HORA FAT. só são herdados por linha de
    # CONTINUAÇÃO PURA - aquela que só traz produto e quilos, sem trazer
    # nenhuma informação própria de carga. Duas situações resetam esses
    # campos (passando a valer só o que a própria linha traz, mesmo que
    # vazio):
    #   1. nova viagem: linha com DATA CARREGAMENTO ou VIAGEM_MAE preenchidos;
    #   2. status próprio: linha que traz o STATUS dela mesma, ou seja, um
    #      bloco de itens em situação diferente dentro do mesmo carregamento
    #      (caso real: itens "PROGRAMADA" listados dentro de uma carga já
    #      "EM TRÂNSITO" - esses ainda não têm NF, e herdar a NF da carga
    #      passaria a impressão errada de que já foram faturados).
    # Assim os outros produtos da mesma carga faturada mostram a NF que
    # realmente é deles (antes apareciam com "-", o que fazia a carga
    # parecer sem nota), sem inventar NF pra quem ainda não tem.
    carry_placas = carry_pedido = carry_nf = carry_fat = ""

    programacao = {}
    nomes_produto = {}
    for r in linhas_csv[idx_cabecalho + 1:]:
        if not any(c.strip() for c in r):
            continue  # linha totalmente em branco entre grupos, se houver

        codigo = _cel(r, idx_codigo_protheus)
        if not codigo:
            continue

        val_data = _cel(r, idx_data)
        val_viagem_mae = _cel(r, idx_viagem_mae)
        val_status = _cel(r, idx_status)
        nova_viagem = bool(val_data or val_viagem_mae)
        # Linha que traz informação própria de carga (nova viagem ou status
        # próprio) zera o que era herdado - o que valer daqui pra frente é
        # o que essa linha declarar.
        if nova_viagem or val_status:
            carry_placas = carry_pedido = carry_nf = carry_fat = ""

        if val_data:
            carry_data = val_data
        if val_viagem_mae:
            carry_viagem_mae = val_viagem_mae
        if val_status:
            carry_status = val_status
        if _cel(r, idx_placas):
            carry_placas = _cel(r, idx_placas)
        if _cel(r, idx_pedido):
            carry_pedido = _cel(r, idx_pedido)
        if _cel(r, idx_nf):
            carry_nf = _cel(r, idx_nf)
        if _cel(r, idx_data_hora_fat):
            carry_fat = _cel(r, idx_data_hora_fat)

        entrada = {
            "data": carry_data,
            "status": carry_status,
            "nf": carry_nf,
            "placas": carry_placas,
            "pedido": carry_pedido,
            "kgProg": _parse_num_br(_cel(r, idx_kg_prog)),
            "kgFat": _parse_num_br(_cel(r, idx_kg_fat)),
        }
        programacao.setdefault(codigo, []).append(entrada)
        if codigo not in nomes_produto:
            nome_produto = _cel(r, idx_produto)
            if nome_produto:
                nomes_produto[codigo] = nome_produto

    for linhas in programacao.values():
        linhas.sort(key=lambda l: _data_para_ordenacao(l["data"]))

    return programacao, nomes_produto


def fmt_kg(v):
    if v is None:
        v = 0
    neg = v < 0
    v = abs(v)
    if v == int(v):
        s = f"{int(v):,}".replace(",", ".")
    else:
        s = f"{v:,.1f}".replace(",", "X").replace(".", ",").replace("X", ".")
    return ("-" if neg else "") + s + " kg"


def slug_nome(nome):
    """Nome do produto em Title Case simples, a partir da Descricao do ERP
    (que normalmente vem toda em maiúsculas)."""
    nome = nome.strip()
    palavras_minusculas = {"de", "da", "do", "das", "dos", "e", "c/", "s/", "a", "com"}
    partes = nome.split(" ")
    out = []
    for i, p in enumerate(partes):
        if i > 0 and p.lower() in palavras_minusculas:
            out.append(p.lower())
        else:
            out.append(p.capitalize() if p.isupper() or p.islower() else p)
    return " ".join(out)


_TAG_RE = re.compile(r"<div\b|</div>")


def _find_matching_div_end(html, div_start):
    """Dado o índice onde começa uma tag <div ...>, encontra o índice logo
    após o </div> que fecha ela (contando divs aninhadas). Retorna -1 se
    não achar (HTML malformado)."""
    primeiro_fechamento_tag = html.find(">", div_start)
    if primeiro_fechamento_tag == -1:
        return -1
    pos = primeiro_fechamento_tag + 1
    profundidade = 1
    for m in _TAG_RE.finditer(html, pos):
        if m.group(0) == "<div":
            profundidade += 1
        else:
            profundidade -= 1
            if profundidade == 0:
                return m.end()
    return -1


def montar_card_novo_html(codigo, nome_produto, peso_cx, cod_cancao, saldo, secao):
    """Monta o HTML de um card novo, no mesmo formato dos existentes.
    O nome exibido prioriza NOME_CANONICO (fixado manualmente); só usa a
    descrição bruta do ERP, formatada, quando o código não está mapeado."""
    if codigo in NOME_CANONICO:
        nome_fmt = NOME_CANONICO[codigo]
    else:
        nome_fmt = slug_nome(nome_produto)
    nome_esc = nome_fmt.replace('"', "&quot;")
    status = "available" if saldo and saldo > 0 else "no-stock"
    stock_html = (
        f'<div class="card-stock"><div class="stock-kg">{fmt_kg(saldo)}</div></div>'
        if status == "available" else
        '<div class="card-stock"><div class="no-stock-tag">SEM ESTOQUE</div></div>'
    )
    peso_txt = f"Cx {peso_cx} kg" if peso_cx else ""
    cancao_txt = cod_cancao if cod_cancao else "—"
    # "new-item" marca o card como recém-criado automaticamente, pro painel
    # destacar ele visualmente e oferecer o botão de renomear. Fica marcado
    # até alguém dispensar no navegador (client-side) - o script preserva
    # essa classe nas próximas atualizações (ver atualizar_html).
    return (
        f'<div class="card {status} new-item" data-name="{nome_esc}" data-section="{secao}" data-status="{status}">'
        f'<div class="card-info"><div class="card-name">{nome_esc}</div>'
        f'<div class="card-code">{codigo} · {peso_txt}</div>'
        f'<div class="card-cancao">Cód. Canção: {cancao_txt}</div></div>'
        f'{stock_html}</div>\n      '
    )


def inserir_cards_novos(html, data, linhas_brutas, programacao=None, nomes_produto_programacao=None):
    """Para códigos que estão na planilha mas não têm card nenhum no HTML,
    cria o card automaticamente. Prefixos fixos (COMPRO, PEFLCANMI) vão
    direto para Alimentos Preparados; os demais são classificados pelo
    texto da descrição do produto (RESFRIADA/CONGELADA/IQF + tipo de
    corte). Só fica sem criar quando a descrição não dá pra classificar
    com segurança - nesse caso o script avisa no log.

    Também cria um card "SEM ESTOQUE" pra qualquer código que apareça na
    planilha de programação de cargas mas não tenha estoque cadastrado
    (produto zerado/descontinuado, mas com carga programada vindo) - assim
    sempre existe um card clicável com o botão "🚚 programação", mesmo sem
    saldo nenhum."""
    programacao = programacao or {}
    nomes_produto_programacao = nomes_produto_programacao or {}

    codigos_existentes = set(re.findall(r'card-code">([^<· ]+)', html))

    codigos_novos = [c for c in data.keys() if c not in codigos_existentes]
    codigos_somente_programacao = [
        c for c in programacao.keys()
        if c not in codigos_existentes and c not in data
    ]
    if not codigos_novos and not codigos_somente_programacao:
        return html, []

    avisos = []
    inseridos = []

    itens = [(c, linhas_brutas.get(c, [])[3] if len(linhas_brutas.get(c, [])) > 3 else c, data.get(c, 0))
             for c in codigos_novos]
    itens += [(c, nomes_produto_programacao.get(c, c), 0) for c in codigos_somente_programacao]

    for codigo, nome_produto, saldo in itens:
        destino = classificar_produto_novo(nome_produto)

        if destino is None:
            # 1º fallback: pede pra IA (Claude) classificar pela descrição,
            # restrito às seções/grupos que realmente existem no painel.
            destino = classificar_com_ia(nome_produto)
            if destino is not None:
                avisos.append(
                    f"código novo '{codigo}' ({nome_produto}) não bateu com "
                    f"nenhuma palavra-chave conhecida - classificado por IA "
                    f"em '{destino[0]}/{destino[1]}'."
                )

        if destino is None:
            # 2º fallback (rede de segurança final): antes o item era
            # descartado aqui (nenhum card criado, só um aviso no log do
            # Actions que ninguém via) - por isso itens novos "sumiam" do
            # painel sem explicação. Agora, mesmo sem conseguir classificar
            # nem por palavra-chave nem por IA, o card é sempre criado, na
            # seção "Não Classificados" - fica visível no painel e só
            # precisa ser movido manualmente pra seção certa quando der.
            destino = ("outros", "NÃO CLASSIFICADO")
            avisos.append(
                f"código novo '{codigo}' ({nome_produto}) não bateu com "
                f"nenhuma palavra-chave conhecida e a IA não teve certeza (ou "
                f"não está configurada) - card criado em 'Não Classificados', "
                f"mova manualmente pra seção certa quando puder."
            )

        secao, grupo_label = destino
        # A descrição do ERP quase sempre tem "CX PP <peso> KG" (às vezes só
        # "CX <peso> KG") - o "PP"/"PV"/etc. no meio fazia o peso não bater
        # e o card novo nascer sem o "Cx X kg" no cabeçalho.
        m_peso = re.search(r"CX\s+(?:[A-ZÇÃÕ]+\s+)?([\d,.]+)\s*KG", nome_produto, re.I)
        peso_cx = m_peso.group(1).replace(".", ",") if m_peso else ""

        cod_cancao = COD_CANCAO_FIXO.get(codigo, "")
        card_html = montar_card_novo_html(codigo, nome_produto, peso_cx, cod_cancao, saldo, secao)

        # Acha a seção certa, depois o group-label certo DENTRO dela, depois
        # a div "cards" logo em seguida - usando contagem de divs balanceada
        # (regex simples falha com divs aninhadas do mesmo nome).
        inserido_ok = False
        secao_start = html.find(f'data-section="{secao}"')
        if secao_start != -1:
            # recua até o "<div class="section"" que contém esse data-section
            secao_div_start = html.rfind('<div class="section"', 0, secao_start)
            secao_end = _find_matching_div_end(html, secao_div_start)
            if secao_end != -1:
                bloco_secao = html[secao_div_start:secao_end]
                grupo_idx = bloco_secao.find(f'<div class="group-label">{grupo_label}</div>')
                if grupo_idx != -1:
                    cards_div_start = bloco_secao.find('<div class="cards">', grupo_idx)
                    if cards_div_start != -1:
                        cards_div_end = _find_matching_div_end(bloco_secao, cards_div_start)
                        if cards_div_end != -1:
                            # cards_div_end aponta logo apos o "</div>" de fechamento;
                            # insere o novo card imediatamente antes desse "</div>".
                            ponto_insercao = cards_div_end - len("</div>")
                            novo_bloco_secao = (
                                bloco_secao[:ponto_insercao]
                                + card_html
                                + bloco_secao[ponto_insercao:]
                            )
                            html = html[:secao_div_start] + novo_bloco_secao + html[secao_end:]
                            inserido_ok = True

        if inserido_ok:
            inseridos.append(codigo)
        else:
            avisos.append(
                f"código novo '{codigo}' seria criado em '{secao}/{grupo_label}' "
                f"mas não encontrei esse grupo no HTML - card NÃO foi criado."
            )

    for a in avisos:
        print("AVISO -", a)
    if inseridos:
        print(f"OK - {len(inseridos)} card(s) novo(s) criado(s) automaticamente: {', '.join(inseridos)}")

    return html, inseridos


def atualizar_html(html, data, validades=None, linhas_brutas=None, programacao=None, nomes_produto_programacao=None):
    validades = validades or {}
    linhas_brutas = linhas_brutas or {}
    programacao = programacao or {}
    nomes_produto_programacao = nomes_produto_programacao or {}

    # ── Cria cards novos ANTES de atualizar os existentes, para que o saldo
    # do card recém-criado já seja processado no mesmo ciclo. Isso inclui
    # tanto itens genuinamente novos no estoque quanto itens que só têm
    # programação de carga (sem estoque cadastrado ainda/mais) - esses
    # últimos nascem "SEM ESTOQUE", só pra existir um card clicável com o
    # botão "🚚 programação". ──
    html, criados_agora = inserir_cards_novos(html, data, linhas_brutas, programacao, nomes_produto_programacao)
    # Códigos que nasceram NESTA rodada: são os únicos que mantêm o selo
    # "NOVO" quando o laço abaixo reescreve a classe do card. Qualquer card
    # que já existia perde o selo (ele vale por uma atualização só).
    criados_agora = set(criados_agora)

    card_starts = [m.start() for m in re.finditer(r'<div class="card[^"]*" data-name=', html)]
    card_starts.append(len(html))

    segments = []
    for i in range(len(card_starts) - 1):
        start, end = card_starts[i], card_starts[i + 1]
        # O "block" entre um card e o próximo pode conter, depois do
        # fechamento do card, HTML estrutural (fechamento de grupo/seção,
        # cabeçalho da próxima seção etc). Isolamos só o HTML do card em
        # si (via contagem balanceada de divs) do "rastro" que vem depois,
        # pra nunca apagar estrutura junto quando um card é removido.
        card_own_end = _find_matching_div_end(html, start)
        if card_own_end == -1 or card_own_end > end:
            card_own_end = end
        block = html[start:card_own_end]
        rastro = html[card_own_end:end]

        m = re.search(r'card-code">([^<]+)</div>', block)
        if not m:
            segments.append(block)
            segments.append(rastro)
            continue
        code = m.group(1).split("·")[0].strip()

        # ── Autocorreção: nome e Cód. Canção sempre seguem as listas fixas
        # (NOME_CANONICO / COD_CANCAO_FIXO), mesmo em cards que já existiam
        # antes dessas listas serem criadas - corrige uma vez e pra sempre. ──
        if code in NOME_CANONICO:
            nome_certo = NOME_CANONICO[code]
            nome_certo_esc = nome_certo.replace('"', "&quot;")
            block = re.sub(
                r'(<div class="card[^"]*" data-name=")[^"]*(")',
                lambda m2: m2.group(1) + nome_certo_esc + m2.group(2),
                block, count=1,
            )
            block = re.sub(
                r'(<div class="card-name">)[^<]*(</div>)',
                lambda m2: m2.group(1) + nome_certo_esc + m2.group(2),
                block, count=1,
            )
        if code in COD_CANCAO_FIXO:
            cancao_certo = COD_CANCAO_FIXO[code]
            block = re.sub(
                r'(<div class="card-cancao">Cód\. Canção: )[^<]*(</div>)',
                lambda m2: m2.group(1) + cancao_certo + m2.group(2),
                block, count=1,
            )

        # ── Gerencia o botão "ver validades" independente do estoque ──
        tem_validade = code in validades and validades[code].get("entries")
        tem_botao = bool(re.search(r'<button class="val-btn[^"]*"[^>]*data-code="' + re.escape(code) + r'"', block))
        if tem_validade and not tem_botao:
            hv = validades[code].get("hv", False)
            if hv:
                btn = f' <button class="val-btn val-btn-alert" onclick="toggleVal(this)" data-code="{code}">⚠️ ver validades</button>'
            else:
                btn = f' <button class="val-btn" onclick="toggleVal(this)" data-code="{code}">📅 ver validades</button>'
            novo_block = re.sub(
                r'(<div class="card-cancao">Cód\. Canção: [^<]*</div>)</div>',
                r'\1' + btn + '</div>', block, count=1,
            )
            if novo_block != block:
                block = novo_block
        elif not tem_validade and tem_botao:
            block = re.sub(r'\s*<button class="val-btn[^"]*"[^>]*>[^<]*</button>', '', block, count=1)
        elif tem_validade and tem_botao:
            # atualiza o estilo do botão (normal <-> alerta) se o hv mudou
            hv = validades[code].get("hv", False)
            nova_classe = "val-btn val-btn-alert" if hv else "val-btn"
            novo_texto = "⚠️ ver validades" if hv else "📅 ver validades"
            block = re.sub(
                r'<button class="val-btn[^"]*"(\s+onclick="toggleVal\(this\)" data-code="' + re.escape(code) + r'">)[^<]*</button>',
                f'<button class="{nova_classe}"' + r'\1' + novo_texto + '</button>',
                block, count=1,
            )

        # ── Gerencia o botão "🚚 programação" independente do estoque ──
        # (fica sempre depois de qualquer botão "ver validades" já tratado
        # acima - o anchor abaixo pega o fim de card-info seja lá o que
        # tiver dentro dele nesse ponto.)
        tem_prog = bool(programacao.get(code))
        tem_botao_prog = bool(re.search(r'<button class="prog-btn"[^>]*data-code="' + re.escape(code) + r'"', block))
        if tem_prog and not tem_botao_prog:
            btn_prog = f' <button class="prog-btn" onclick="toggleProg(this)" data-code="{code}">🚚 programação</button>'
            novo_block = re.sub(
                r'(<div class="card-info">.*?)(</div>\s*<div class="card-stock">)',
                lambda m2: m2.group(1) + btn_prog + m2.group(2),
                block, count=1, flags=re.S,
            )
            if novo_block != block:
                block = novo_block
        elif not tem_prog and tem_botao_prog:
            block = re.sub(r'\s*<button class="prog-btn"[^>]*>[^<]*</button>', '', block, count=1)

        if code not in data:
            if tem_prog:
                # Exceção: o produto saiu da planilha de estoque (acabou/
                # descontinuado), mas ainda tem programação de carga vindo -
                # em vez de apagar o card, mantém ele marcado "SEM ESTOQUE",
                # só pra continuar existindo um card clicável com o botão
                # "🚚 programação" (é só isso que sobra dele nesse caso).
                val = 0
            else:
                # Regra: se o código não aparece mais na planilha de estoque
                # nem tem programação pendente, o produto foi descontinuado/
                # removido do ERP - o card some do painel (não fica com o
                # saldo antigo parado). Se o código reaparecer numa planilha
                # futura, o card é recriado automaticamente. O "rastro"
                # (fechamentos de grupo/seção, próximo cabeçalho) é sempre
                # preservado, mesmo quando o card é removido.
                segments.append(rastro)
                continue
        else:
            val = data[code]
        was_nostock = 'data-status="no-stock"' in block
        classe_atual_m = re.search(r'<div class="card ([^"]*)" data-name=', block)
        tinha_has_obs = classe_atual_m and "has-obs" in classe_atual_m.group(1)
        # O selo "NOVO" (classe "new-item", ver montar_card_novo_html) vale
        # por UMA atualização só: fica apenas nos cards criados nesta rodada.
        # Card que já existia com o selo perde ele aqui - o produto apareceu
        # na atualização anterior, então não é mais novidade.
        tinha_new_item = code in criados_agora
        sufixo_new_item = " new-item" if tinha_new_item else ""
        if val and val > 0:
            block = re.sub(
                r'(<div class="card )[^"]*(" data-name="[^"]*" data-section="[^"]*" data-status=")[^"]*(")',
                rf"\1available{sufixo_new_item}\g<2>available\3", block, count=1,
            )
            block = re.sub(
                r'<div class="card-stock">.*?</div>\s*</div>',
                f'<div class="card-stock"><div class="stock-kg">{fmt_kg(val)}</div></div>',
                block, count=1, flags=re.S,
            )
            if was_nostock:
                block = re.sub(r'\s*<div class="obs-wrap">.*?</div>\s*', "\n", block, flags=re.S)
                block = block.replace(" has-obs", "").replace("has-obs ", "").replace("has-obs", "")
        else:
            partes_classe = ["no-stock"]
            if tinha_has_obs:
                partes_classe.append("has-obs")
            if tinha_new_item:
                partes_classe.append("new-item")
            classe_nova = " ".join(partes_classe)
            block = re.sub(
                r'(<div class="card )[^"]*(" data-name="[^"]*" data-section="[^"]*" data-status=")[^"]*(")',
                rf"\1{classe_nova}\g<2>no-stock\3", block, count=1,
            )
            block = re.sub(
                r'<div class="card-stock">.*?</div>\s*</div>',
                '<div class="card-stock"><div class="no-stock-tag">SEM ESTOQUE</div></div>',
                block, count=1, flags=re.S,
            )
        segments.append(block)
        segments.append(rastro)

    new_html = html[: card_starts[0]] + "".join(segments)

    # Atualiza os dados de validade usados pelos selos automáticos (vence em Xd / vencido)
    new_html = re.sub(
        r"var VALIDADES = (\{.*?\})\s*;",
        "var VALIDADES = " + json.dumps(validades, ensure_ascii=False) + ";",
        new_html, count=1, flags=re.S,
    )

    # Atualiza os dados usados pelo botão "🚚 programação" de cada card
    new_html = re.sub(
        r"var PROGRAMACAO = (\{.*?\})\s*;",
        "var PROGRAMACAO = " + json.dumps(programacao, ensure_ascii=False) + ";",
        new_html, count=1, flags=re.S,
    )

    # Atualiza o histórico de tendência (mantém últimos 4 ciclos)
    m = re.search(r"var HISTORICO = (\{.*?\})\s*;", new_html, re.S)
    if m:
        hist = json.loads(m.group(1))
        for code, val in data.items():
            arr = hist.get(code, [])
            arr.append(float(val))
            hist[code] = arr[-4:]
        new_hist_str = json.dumps(hist, ensure_ascii=False)
        new_html = new_html[: m.start(1)] + new_hist_str + new_html[m.end(1):]

    # Atualiza o horário exibido como "Atualizado hoje às HHhMM" (horário de Brasília, UTC-3)
    agora_brt = datetime.now(timezone.utc) - timedelta(hours=3)
    novo_timestamp = agora_brt.strftime("%Y-%m-%dT%H:%M:%S")
    new_html = re.sub(
        r'var ULTIMA_ATUALIZACAO = "[^"]*";',
        f'var ULTIMA_ATUALIZACAO = "{novo_timestamp}";',
        new_html,
    )

    # Atualiza também o selo de data no cabeçalho (badge-date), que é o campo
    # que decide se o painel mostra "hoje"/"ontem"/"há X dias"
    nova_data_badge = agora_brt.strftime("%d/%m/%Y")
    new_html = re.sub(
        r'<span class="badge-date">[^<]*</span>',
        f'<span class="badge-date">{nova_data_badge}</span>',
        new_html,
    )
    new_html = re.sub(
        r'<title>Estoque Apucarana – [^<]*</title>',
        f'<title>Estoque Apucarana – {nova_data_badge}</title>',
        new_html,
    )

    return new_html


def fmt_preco(v):
    v = (v or "").strip()
    if not v:
        return None
    # valores não numéricos (ex: "—") são mantidos como estão
    limpo = v.replace(".", "").replace(",", ".")
    try:
        num = float(limpo)
    except ValueError:
        return v
    return f"{num:.2f}".replace(".", ",")


def _normalizar_nome_preco(txt):
    """Normaliza um nome de produto pra comparação: tira acento, baixa a
    caixa, troca pontuação (/()., e apóstrofos) por espaço e colapsa
    espaços. Usada tanto pro NOME da planilha quanto pro data-name do card,
    porque um raramente é digitado igual ao outro (acento, barra, abreviação)."""
    nome = _sem_acento(txt or "").lower()
    nome = re.sub(r"[/().'’\"“”+\-]", " ", nome)
    nome = re.sub(r"\s+", " ", nome).strip()
    return nome


def _palavras_nome_preco(nome_normalizado):
    """Conjunto de palavras de um nome já normalizado, usado no pareamento
    por semelhança (ver _achar_info em atualizar_precos_html)."""
    return {p for p in re.split(r"[^a-z0-9,]+", nome_normalizado) if p}


